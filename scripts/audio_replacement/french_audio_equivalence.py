"""Canonical spelling only: preserve signs, decimal positions and hour values."""
import re
import unicodedata
from text_to_num import alpha2digit

def norm(text):
 text=text.replace('’',"'").replace('\u202f',' ')
 # Grouped telephone numbers are identifiers, not decimal quantities.
 text=re.sub(r'\b0[1-9](?:[ .-]\d{2}){4}\b',lambda m:m[0].replace(' ','').replace('.','').replace('-',''),text)
 text=text.replace('€',' euros ')
 text=re.sub(r'(?i)(\d+)\s*°\s*C\b',r'\1 degrés',text)
 text=re.sub(r'(?m)^\s*-\s+(?=\d+\s*h(?:\s|\d))','',text)
 text=re.sub(r'(?<!\w)[−-]\s*(?=\d)','moins ',text)
 text=re.sub(r'(?<!\w)\+\s*(?=\d)','plus ',text)
 text=re.sub(r'(\d+)[,.](\d+)',lambda m:m[1]+' virgule '+(m[2].rstrip('0') or '0'),text)
 text=re.sub(r'\b\d{1,3}(?:[ ]\d{3})+\b',lambda m:m[0].replace(' ',''),text)
 # "Pour cent" is a unit, not an additional cardinal 100. Mixed spaces
 # and hyphens in ASR French numerals also need canonical spelling first.
 text=re.sub(r'(?i)\bpour[ -]?cents?\b','%',text)
 text=re.sub(r'(?i)\bquatre\s+vingts?\b','quatre-vingt',text)
 text=re.sub(r'(?i)\bsoixante\s+dix\b','soixante-dix',text)
 text=re.sub(r'(?i)\b((?:vingt|trente|quarante|cinquante|soixante|septante|huitante|nonante)[ -]+et[ -]+)une\b',r'\1un',text)
 text=re.sub(r'(?i)\b(quatre[ -]+vingt[ -]+)une\b',r'\1un',text)
 text=re.sub(r'(?i)\bune\s+(heures?)\b',r'un \1',text)
 text=re.sub(r'(?i)\bzero\b','zéro',text)
 text=alpha2digit(text,'fr',threshold=0)
 text=re.sub(r'\b0\s?[1-9](?:[ .-]\d{2}){4}\b',lambda m:re.sub(r'[ .-]','',m[0]),text)
 def phone_identifier(match):
  digits=re.sub(r'[ .-]','',match[2])
  return match[1]+(digits if len(digits)==10 else match[2])
 text=re.sub(r'(?i)\b((?:au|le|numero|portable|telephone)\s+)(0\d*(?:[ .-]+\d+)*)',phone_identifier,text)
 text=re.sub(r'(?i)\b(\d+)\s*(?:kilos?|kg)\s+et\s+demi\b',r'\1 virgule 5 kg',text)
 text=re.sub(r'(?i)\bune\s+heure\b','1 heure',text)
 # A hyphen introducing a numeric reply is a dialogue marker in these
 # transcripts. Negative temperatures and signed amounts remain unchanged.
 text=re.sub(r'(?i)\b(\d+)\s+heures?\s+et\s+(\d+)\s+minutes?\b',r'\1h\2',text)
 text=re.sub(r'(?i)\b((?:au|code(?: est)?(?: le)?|numero(?: est)?(?: le)?)\s+)((?:\d+[ -])+\d+)\b',lambda m:m[1]+re.sub(r'[ -]','',m[2]),text)
 text=re.sub(r'\b118[ -](\d{3})\b',r'118\1',text)
 text=re.sub(r'(?i)(\d+)\s*(?:heures?|h)(?![a-zà-ÿ])\s*(?:et\s+)?demie?\b',r'\1h30',text)
 text=re.sub(r'\bM\.\s+(?=[A-ZÀ-Ý])','Monsieur ',text)
 text=re.sub(r'(?i)\bmme\b(?=\s*[,;]?\s*messieurs\b)','Mesdames',text)
 text=re.sub(r'\bMme\.?\s+','Madame ',text)
 text=re.sub(r'\bM\s+me\s+','Madame ',text)
 text=re.sub(r'(?i)\bn[°º]\s*(?=\d)','numéro ',text)
 text=re.sub(r'(?i)(\d+)\s*(?:heures?|h)(?![a-zà-ÿ])\s*(\d*)',lambda m: str(int(m[1]))+'h'+str(int(m[2] or '0')).zfill(2),text)
 text=re.sub(r'(?i)\b(\d+)(?:er|e|ème|eme)\b',r'\1',text)
 text=unicodedata.normalize('NFD',text.casefold());text=''.join(c for c in text if unicodedata.category(c)!='Mn')
 text=re.sub(r'[^a-z0-9]+',' ',text).strip()
 # These are alternative spellings of the same interjection, not different
 # dialogue words. Keep surrounding content, negation and numbers intact.
 text=re.sub(r'\b(?:oh la la|ou la la|oulala|holala|ouhlala)\b','oh lala',text)
 text=re.sub(r'\b(?:waouh|waw|wow|wouah)\b','waouh',text)
 return text

assert norm('À trois heures quarante.') == norm('À 3 h 40.')
assert norm('À trois heures quarante.') != norm('À 15 h 40.')
assert norm('Il fera -5 degrés.') == norm('Il fera moins cinq degrés.')
assert norm('Il fera -5 degrés.') != norm('Il fera 5 degrés.')
assert norm('Il faut 3,5 litres.') != norm('Il faut 35 litres.')
assert norm('Il faut 3,5 litres.') == norm('Il faut 3.5 litres.')
assert norm('Avec quatre enfants.') == norm('Avec 4 enfants.')

assert norm('À 13 heures.') == norm('À 13h00.')
assert norm('À huit heures et demie.') == norm('À 8 h 30.')
assert norm('Appelez le 118-712.') == norm('Appelez le 118712.')
assert norm('Oh là là, où sont mes clés ?') == norm('Oulala, où sont mes clés ?')
assert norm('Oulala, il est 8 h.') != norm('Oulala, il est 10 h.')
assert norm('Oulala, elle ne vient pas.') != norm('Oulala, elle vient.')
assert norm('La remise est de vingt-cinq pour cent.') == norm('La remise est de 25 %.')
assert norm('Il y a cent personnes.') != norm('Il y a une personne.')
assert norm('En mille neuf cent quatre vingt-dix.') == norm('En 1990.')
assert norm('La remise est de cent pour cent.') == norm('La remise est de 100 %.')
assert norm('Appelez au 03.21.96.55.41.') == norm('Appelez au 03 21 96 55 41.')
assert norm('Envoyez un texto au 38 20.') == norm('Envoyez un texto au 3820.')
assert norm('Le code est le 51 89.') == norm('Le code est le 5189.')
assert norm('Il dure deux heures et vingt minutes.') == norm('Il dure 2h20.')
assert norm('Je me couche à une heure du matin.') == norm('Je me couche à 1h du matin.')
assert 'h00' not in norm('Il y a quinze hôtesses et deux hibillets.')
assert norm('Il y a quinze hôtesses.') != norm('Il y a quinze heures.')
assert norm('Il fait -5 °C.') == norm('Il fait moins cinq degrés.')
assert norm('Il fait 5 °F.') != norm('Il fait 5 °C.')
assert norm('À vingt et une heures.') == norm('À 21 h.')
assert norm('Je prends deux kilos et demi.') == norm('Je prends 2,5 kg.')
assert norm('La remise est de quatre-vingt-deux pour cents.') == norm('La remise est de 82 %.')
assert norm('J’ai vingt et une paires de chaussures.') == norm('J’ai 21 paires de chaussures.')
assert norm('J’ai vingt et une paires de chaussures.') != norm('J’ai 20 paires de chaussures.')
assert norm('Appelez le 0 800 63 10 10.') == norm('Appelez le 0800 63 10 10.')
assert norm('Appelez le 0 800 63 10 10.') != norm('Appelez le 0800 63 10 11.')
assert norm('Elle pèse 3,100 kg.') == norm('Elle pèse 3,1 kg.')
assert norm('Le prix est de 5,50 euros.') == norm('Le prix est de 5,5 euros.')
assert norm('Le prix est de 5,50 euros.') != norm('Le prix est de 55 euros.')
assert norm('Mme, Messieurs, votre attention.') == norm('Mesdames, Messieurs, votre attention.')
assert norm('Waw, sympa ton pantalon !') == norm('Waouh, sympa ton pantalon !')
