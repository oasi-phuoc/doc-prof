import {readFile,writeFile} from 'node:fs/promises'
import {PNG} from 'pngjs'
const groups=['classic','zodiac-a','zodiac-b','nature','spirits'],crops=[],masks=[]
for(const group of groups){
 const image=PNG.sync.read(await readFile(`public/lib/images/interactive/mascots-health-${group}.png`)),cw=image.width/4,ch=image.height/6
 for(let row=0;row<6;row++)for(let col=0;col<4;col++){
  const seen=new Uint8Array(cw*ch),queue=new Uint32Array(cw*ch);let biggest={count:0,left:0,top:0,right:cw-1,bottom:ch-1},body=new Uint32Array()
  const opaque=i=>image.data[((row*ch+Math.floor(i/cw))*image.width+col*cw+i%cw)*4+3]>80
  for(let i=0;i<cw*ch;i++){
   if(seen[i]||!opaque(i))continue
   let start=0,end=1,left=cw,top=ch,right=0,bottom=0;queue[0]=i;seen[i]=1
   while(start<end){const at=queue[start++],x=at%cw,y=Math.floor(at/cw);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y)
    for(const [dx,dy] of [[1,0],[-1,0],[0,1],[0,-1]]){const xx=x+dx,yy=y+dy,next=yy*cw+xx;if(xx<0||xx>=cw||yy<0||yy>=ch||seen[next]||!opaque(next))continue;seen[next]=1;queue[end++]=next}
   }
   if(end>biggest.count){biggest={count:end,left,top,right,bottom};body=queue.slice(0,end)}
  }
  if(biggest.count<cw*ch*.03)throw new Error(`Missing character in ${group}/${row}/${col}`)
  const lefts=new Int16Array(ch).fill(cw),rights=new Int16Array(ch).fill(-1)
  for(const at of body){const x=at%cw,y=Math.floor(at/cw);lefts[y]=Math.min(lefts[y],x);rights[y]=Math.max(rights[y],x)}
  const leftEdge=[],rightEdge=[]
  for(let y=Math.max(0,biggest.top-2);y<=Math.min(ch-1,biggest.bottom+2);y+=8){
   const end=Math.min(ch,y+8),nearStart=Math.max(0,y-2),nearEnd=Math.min(ch,end+2);let l=cw,r=-1
   for(let yy=nearStart;yy<nearEnd;yy++){l=Math.min(l,lefts[yy]);r=Math.max(r,rights[yy])}
   if(r<0)continue
   l=Math.max(0,l-2);r=Math.min(cw,r+3)
   leftEdge.push([l,y],[l,end]);rightEdge.push([r,y],[r,end])
  }
  const points=[...leftEdge,...rightEdge.reverse()],simple=points.filter((p,i)=>{const prev=points[(i+points.length-1)%points.length],next=points[(i+1)%points.length];return !((p[0]===prev[0]&&p[0]===next[0])||(p[1]===prev[1]&&p[1]===next[1]))})
  masks.push(simple.map(([x,y])=>[Number((x/cw*100).toFixed(4)),Number((y/ch*100).toFixed(4))]))
  crops.push([Math.max(0,biggest.top-2)/ch*100,Math.max(0,cw-biggest.right-3)/cw*100,Math.max(0,ch-biggest.bottom-3)/ch*100,Math.max(0,biggest.left-2)/cw*100].map(v=>Number(v.toFixed(4))))
 }
}
await writeFile('src/interactive/duel/combat-crops.generated.ts','// Generated by scripts/mascot-combat-crops.mjs from alpha-connected body bounds.\n// CSS clipping only: original PNG bytes are never modified. Each tuple: top/right/bottom/left %.\nexport const COMBAT_CROPS = '+JSON.stringify(crops)+' as const\nexport const COMBAT_MASKS = '+JSON.stringify(masks)+' as const\n')
console.log(`${crops.length} isolated combat sprite bounds generated`)
