import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const results = []
const button = (page, name) => page.getByRole('button', { name, exact: true })
async function navigate(page, index) {
  await page.getByRole('button', { name: /^Choisir une question ·/ }).click()
  await page.getByRole('dialog', { name: 'Choisir une question', exact: true }).locator('li button').nth(index).click()
}
async function reveal(page) {
  await button(page, 'Signal : levez vos cartes').click()
  await button(page, 'Discuter').click()
  await button(page, 'Enseignant : révéler').click()
}
try {
  for (const [width, height] of [[390, 700], [1366, 768]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
    await page.goto(`${base}/interactif/demo`)
    await page.locator('.ci-launch:enabled').waitFor({ timeout: 120000 })
    await page.clock.install()
    await page.clock.pauseAt(new Date(Date.now() + 1000))
    await page.locator('.ci-launch').click()
    await page.locator('.ci-controls').waitFor()
    await page.clock.runFor(3200)
    assert.equal(await page.locator('.ci-timer-value').innerText(), '0:27')
    await navigate(page, 1)
    await page.clock.runFor(1200)
    assert.equal(await page.locator('.ci-timer-value').innerText(), '0:29')
    await navigate(page, 0)
    assert.equal(await page.locator('.ci-timer-value').innerText(), '0:27')
    await navigate(page, 1)
    assert.equal(await page.locator('.ci-timer-value').innerText(), '0:29')
    await button(page, 'Signal : levez vos cartes').click()
    await button(page, 'Discuter').click()
    await navigate(page, 0)
    assert.equal(await page.locator('.ci-answer-key').count(), 0)
    await reveal(page)
    const initialOrder = await page.locator('.ci-answer-content > span').allTextContents()
    const initialLetter = await page.locator('.ci-answer-key .ci-card-badge b').innerText()
    await navigate(page, 1)
    await button(page, 'Enseignant : révéler').waitFor()
    assert.equal(await page.locator('.ci-answer-key').count(), 0)
    await navigate(page, 0)
    assert.equal(await page.locator('.ci-answer-key').count(), 1)
    await page.getByRole('button', { name: /^Choisir une question ·/ }).click()
    const nav = page.getByRole('dialog', { name: 'Choisir une question', exact: true })
    const box = await nav.boundingBox()
    assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= height)
    await nav.getByRole('button', { name: 'Réessayer cette question', exact: true }).click()
    const retry = page.getByRole('dialog', { name: 'Réessayer cette question ?', exact: true })
    await retry.getByRole('button', { name: 'Nouvelle tentative', exact: true }).click()
    assert.equal(await page.locator('.ci-answer-key, .ci-answer-muted').count(), 0)
    assert.equal(await page.locator('.ci-timer-value').innerText(), '0:30')
    assert.notDeepEqual(await page.locator('.ci-answer-content > span').allTextContents(), initialOrder)
    await reveal(page)
    assert.notEqual(await page.locator('.ci-answer-key .ci-card-badge b').innerText(), initialLetter)
    await page.getByRole('button', { name: /^Choisir une question ·/ }).click()
    const lastIndex = await nav.locator('li').count() - 1
    await nav.locator('li button').last().click()
    await page.locator('.ci-sequence').waitFor()
    await button(page, 'Choisir la scène 1, place 1').focus(); await page.keyboard.press('ArrowRight')
    const scenes = await page.locator('.ci-sequence .ci-image-zoom > img').evaluateAll((images) => images.map((image) => image.alt))
    assert.deepEqual(scenes.slice(0, 2), ['Scène 2', 'Scène 1'])
    await button(page, 'Commencer l’échange').click()
    await button(page, 'Proposer une relance').click()
    const hints = await page.locator('.ci-oral-hints p').allTextContents()
    assert.equal(hints.length, 1)
    await navigate(page, 0)
    assert.equal(await page.locator('.ci-answer-key').count(), 1)
    await navigate(page, lastIndex)
    assert.deepEqual(await page.locator('.ci-sequence .ci-image-zoom > img').evaluateAll((images) => images.map((image) => image.alt)), scenes)
    assert.deepEqual(await page.locator('.ci-oral-hints p').allTextContents(), hints)
    await button(page, 'Quitter la séance').click()
    await page.getByRole('button', { name: /Reprendre la séance/ }).waitFor()
    await page.reload()
    await page.clock.resume()
    await page.locator('.ci-launch:enabled').waitFor()
    await page.clock.pauseAt(new Date((await page.evaluate(() => Date.now())) + 100))
    await page.getByRole('button', { name: /Reprendre la séance/ }).click()
    await page.locator('.ci-sequence').waitFor()
    assert.deepEqual(await page.locator('.ci-sequence .ci-image-zoom > img').evaluateAll((images) => images.map((image) => image.alt)), scenes)
    assert.deepEqual(await page.locator('.ci-oral-hints p').allTextContents(), hints)
    await navigate(page, 0)
    assert.equal(await page.locator('.ci-answer-key').count(), 1)
    assert.notEqual(await page.locator('.ci-answer-key .ci-card-badge b').innerText(), initialLetter)
    await page.screenshot({ path: `docs/interactive/screenshots/navigation-retry-${width}.png` })
    await button(page, 'Terminer la séance').click()
    await button(page, 'Terminer et voir le bilan').click()
    await page.locator('.ci-summary').waitFor()
    assert.match(await page.locator('.ci-summary').innerText(), /1 question\(s\) abordée\(s\), 9 passée\(s\)/)
    assert.equal(await page.locator('.ci-attempt-history').count(), 1)
    assert.match(await page.locator('.ci-attempt-history summary').innerText(), /Tentatives précédentes \(1\)/)
    await button(page, 'Revoir les questions').click()
    assert.equal(await page.locator('.ci-answer-key').count(), 1)
    assert.deepEqual(errors, [])
    results.push({ viewport: `${width}x${height}`, navigation: 'thinking, discussion and reveal restored independently; unvisited questions stay unrevealed', countdowns: '27 s and 29 s retained separately', retry: 'new card order and correct slot; previous result archived; one active result', oral: 'image order and hint preserved across navigation and reload', summary: 'one current corrected question, nine skipped, previous attempt separately retained; review reopens correctly', errors })
    await page.close()
  }
  await writeFile('docs/interactive/navigation-results.json', JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
