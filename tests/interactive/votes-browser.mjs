import { skipQuestion } from './browser-actions.mjs'
import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { classroomRecipe } from './classroom-fixture.mjs'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const results = []
try {
  for (const [width, height] of [[1366, 768], [390, 700]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
    await page.goto(`${base}/interactif/demo`)
    await page.locator('.ci-launch:enabled').waitFor({ timeout: 120000 })
    await page.locator('.ci-launch').click()
    await page.locator('.ci-controls').waitFor()
    assert.equal(await page.getByRole('button', { name: 'Compter', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Signal : levez vos cartes', exact: true }).click()
    await page.getByRole('button', { name: 'Compter', exact: true }).click()
    let panel = page.getByRole('dialog', { name: 'Comptage saisi par l’enseignant', exact: true })
    await panel.waitFor()
    const bounds = await panel.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width && bounds.y + bounds.height <= height)
    assert.equal(await panel.getByRole('checkbox', { name: 'Montrer à la classe', exact: true }).isChecked(), false)
    await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte A', exact: true }).fill('3')
    await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte B', exact: true }).fill('4')
    await panel.getByRole('spinbutton', { name: 'Présents (facultatif)', exact: true }).fill('6')
    await panel.getByRole('button', { name: 'Valider le comptage', exact: true }).click()
    assert.match(await panel.getByRole('alert').innerText(), /total de 7 votes dépasse les 6 présents/)
    await panel.getByRole('spinbutton', { name: 'Présents (facultatif)', exact: true }).fill('8')
    await panel.getByRole('button', { name: 'Majorité à revoir', exact: true }).click()
    await panel.getByRole('button', { name: 'Valider le comptage', exact: true }).click()
    assert.equal(await page.locator('dialog[open]').count(), 0)
    assert.equal(await page.locator('.ci-manual-vote').count(), 0)
    assert.equal(await page.locator('.ci-answer-correct, .ci-margin-answer, .ci-reveal').count(), 0)
    await page.getByRole('button', { name: 'Compter', exact: true }).click()
    panel = page.getByRole('dialog', { name: 'Comptage saisi par l’enseignant', exact: true })
    assert.equal(await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte A', exact: true }).inputValue(), '3')
    await panel.getByRole('checkbox', { name: 'Montrer à la classe', exact: true }).check()
    await panel.getByRole('button', { name: 'Valider le comptage', exact: true }).click()
    await page.locator('.ci-manual-vote').waitFor()
    assert.match(await page.locator('.ci-manual-vote').innerText(), /A : 3 · B : 4/)
    assert.equal(await page.locator('.ci-answer-correct, .ci-margin-answer, .ci-reveal').count(), 0)
    if (width < 700) for (const element of await page.locator('.ci-answer:visible, .ci-controls:visible').all()) {
      const box = await element.boundingBox()
      assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= width + 1 && box.y + box.height <= height + 1, `Manual sharing pushed game off screen: ${JSON.stringify(box)}`)
    }
    await page.getByRole('button', { name: 'Quitter la séance', exact: true }).click()
    await page.getByRole('button', { name: /Reprendre la séance/ }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: /Reprendre la séance/ }).click()
    await page.locator('.ci-manual-vote').waitFor()
    assert.match(await page.locator('.ci-manual-vote').innerText(), /Total saisi : 7 \/ 8 présents/)
    await page.getByRole('button', { name: 'Discuter', exact: true }).click()
    await page.getByRole('button', { name: 'Enseignant : révéler', exact: true }).click()
    await page.getByRole('button', { name: 'Question suivante', exact: true }).click()
    while (await page.getByRole('button', { name: 'Passer', exact: true }).count()) await skipQuestion(page)
    await page.locator('.ci-summary').waitFor()
    assert.equal(await page.locator('.ci-vote-summary').count(), 1, 'Questions with no counts must have no numeric placeholder')
    assert.match(await page.locator('.ci-vote-summary').innerText(), /D’après votre comptage : \d vote\(s\) sur 7/)
    assert.equal(await page.locator('.ci-summary').getByText(/%/).count(), 0)
    const mark = page.getByRole('group', { name: /^Marque enseignant :/ }).first().getByRole('button', { name: 'À revoir', exact: true })
    await mark.click()
    assert.equal(await mark.getAttribute('aria-pressed'), 'true')
    await page.getByRole('textbox', { name: 'Observations', exact: true }).fill('Revoir les retenues au prochain cours.')
    await page.getByRole('textbox', { name: 'Observations', exact: true }).blur()
    await page.reload()
    await page.locator('.ci-launch:enabled').waitFor()
    await page.getByRole('button', { name: 'Revoir le bilan', exact: true }).click()
    await page.locator('.ci-summary').waitFor()
    assert.equal(await page.getByRole('textbox', { name: 'Observations', exact: true }).inputValue(), 'Revoir les retenues au prochain cours.')
    assert.equal(await page.getByRole('group', { name: /^Marque enseignant :/ }).first().getByRole('button', { name: 'À revoir', exact: true }).getAttribute('aria-pressed'), 'true')
    const stored = await page.evaluate(async () => {
      const db = await new Promise((resolve) => { const request = indexedDB.open('clairfle-interactive'); request.onsuccess = () => resolve(request.result) })
      const records = await new Promise((resolve) => { const request = db.transaction('sessions').objectStore('sessions').getAll(); request.onsuccess = () => resolve(request.result) })
      db.close()
      return records.find((record) => record.checkpoint?.state.note === 'Revoir les retenues au prochain cours.')
    })
    assert.equal(stored.schemaVersion, 4)
    assert.equal(stored.events.length, 0)
    assert.equal(stored.checkpoint.state.note, 'Revoir les retenues au prochain cours.')
    assert.ok(Object.values(stored.checkpoint.state.teacherMarks).includes('review'))
    assert.deepEqual(errors, [])
    results.push({ viewport: `${width}x${height}`, validation: 'rejects total above attendance', privacy: 'default hidden; explicit shared counts contain no answer key', persistence: 'counts, visibility, notes and teacher marks journaled', summary: 'one counted question, teacher provenance, no class percentage', errors })
    await page.close()
  }
  const page = await browser.newPage()
  await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
  await page.goto(`${base}/generateur`)
  await page.evaluate((recipe) => { history.pushState({ clairfleInteractive: { recipe, name: 'Comptage de deux questions' } }, '', '/interactif'); dispatchEvent(new PopStateEvent('popstate')) }, await classroomRecipe())
  await page.locator('.ci-launch:enabled').waitFor({ timeout: 120000 })
  await page.locator('.ci-launch').click()
  // Skip individual questions until the shared recording's paired round.
  while (!/Questions /.test(await page.locator('.ci-progress').innerText())) await skipQuestion(page)
  await page.getByRole('button', { name: 'Signal : levez vos cartes', exact: true }).click()
  await page.getByRole('button', { name: 'Compter', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Comptage saisi par l’enseignant', exact: true })
  assert.equal(await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte A', exact: true }).isEnabled(), true)
  assert.equal(await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte D', exact: true }).isEnabled(), false)
  await panel.getByRole('combobox', { name: 'Question à compter', exact: true }).selectOption('1')
  assert.equal(await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte A', exact: true }).isEnabled(), false)
  assert.equal(await panel.getByRole('spinbutton', { name: 'Nombre de votes, carte D', exact: true }).isEnabled(), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('dialog[open]').count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Discuter', exact: true }).isVisible(), true)
  results.push({ pairedAudio: 'A–C and D–F counted separately; inactive slots disabled; Escape cancels without revealing' })
  await writeFile('docs/interactive/manual-count-results.json', JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
