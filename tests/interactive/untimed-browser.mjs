import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 700 }, hasTouch: true })
  await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
  await page.goto(`${base}/interactif/demo`)
  await page.locator('.ci-launch:enabled').waitFor({ timeout: 120000 })
  await page.getByRole('button', { name: 'Mode de jeu', exact: true }).click()
  const enabled = page.getByRole('checkbox', { name: 'Activer le minuteur', exact: true })
  assert.equal(await enabled.isEnabled(), true)
  await enabled.uncheck()
  await page.getByRole('spinbutton', { name: 'Temps de réflexion (secondes)', exact: true }).fill('5')
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await page.locator('.ci-launch').click()
  await page.getByText('Sans minuteur', { exact: true }).waitFor()
  await page.clock.runFor(61000)
  assert.equal(await page.locator('.ci-reveal').count(), 0)
  assert.equal(await page.locator('.ci-answer:enabled').count(), 6)
  assert.match(await page.locator('.ci-controls').innerText(), /à ton rythme/)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.getByRole('button', { name: /1.?559/ }).click()
  await page.locator('.ci-reveal').waitFor()
  assert.equal(await page.locator('.ci-round-question .ci-explanation, .ci-round-question .ci-model-answer').count(), 0)
  await page.clock.runFor(5100)
  await page.locator('.ci-progress').filter({ hasText: 'Question 2 /' }).waitFor()
  await page.getByRole('button', { name: 'Régler le minuteur', exact: true }).click()
  assert.equal(await enabled.isEnabled(), true)
  assert.equal(await enabled.isChecked(), false)
  await enabled.check()
  await page.getByRole('button', { name: 'Fermer les réglages', exact: true }).click()
  await page.clock.runFor(5100)
  await page.locator('.ci-reveal').waitFor()
  assert.match(await page.locator('.ci-correction-status').innerText(), /Temps écoulé/)
  assert.equal(await page.locator('.ci-round-question .ci-explanation, .ci-round-question .ci-model-answer').count(), 0)
  await page.clock.runFor(5100)
  await page.locator('.ci-progress').filter({ hasText: 'Question 3 /' }).waitFor()
  await page.locator('.ci-answer').first().click()
  await page.locator('.ci-reveal').waitFor()
  assert.equal(await page.locator('.ci-round-question .ci-explanation, .ci-round-question .ci-model-answer').count(), 0, 'Geometry must not repeat the answer below the cards')
  await page.getByRole('button', { name: 'Quitter la séance', exact: true }).click()
  await page.locator('.ci-launch:enabled').waitFor()
  await enabled.uncheck()
  await page.getByRole('button', { name: 'Tout désélectionner', exact: true }).click()
  await page.locator('.ci-question-list fieldset').last().getByRole('checkbox').first().check()
  await page.locator('.ci-launch:enabled').waitFor()
  await page.locator('.ci-launch').click()
  await page.getByRole('button', { name: 'Voir le modèle', exact: true }).waitFor()
  await page.clock.runFor(61000)
  assert.equal(await page.locator('.ci-reveal').count(), 0)
  await page.getByRole('button', { name: 'Voir le modèle', exact: true }).click()
  await page.locator('.ci-model-answer').waitFor()
  console.log('PASS: Solo timer optional before and during play; no timeout when disabled; automatic feedback retained; no duplicate correction under cards; untimed open production remains usable.')
} finally { await browser.close() }
