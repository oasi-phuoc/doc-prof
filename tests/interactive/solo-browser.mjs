import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const results = []
try {
  for (const [width, height] of [[1366, 768], [1920, 1080], [390, 844]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    page.setDefaultTimeout(30000)
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
    await page.goto(`${base}/interactif/demo`)
    await page.getByRole('button', { name: /Commencer la séance/ }).waitFor({ timeout: 120000 })
    assert.equal(await page.getByRole('button', { name: 'Mode de jeu', exact: true }).getAttribute('aria-pressed'), 'false')
    await page.getByRole('button', { name: 'Mode de jeu', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Mode de jeu', exact: true }).getAttribute('aria-pressed'), 'true')
    assert.equal(await page.getByRole('dialog', { name: 'Choisir le mode de jeu' }).count(), 0)
    await page.getByRole('spinbutton', { name: 'Temps de réflexion (secondes)' }).fill('5')
    await page.clock.install()
    await page.clock.pauseAt(new Date(Date.now() + 1000))
    await page.getByRole('button', { name: /Commencer la séance/ }).click()
    await page.locator('.ci-controls').waitFor()
    assert.equal(await page.locator('.ci-answer:enabled').count(), 6)
    assert.equal(await page.getByRole('button', { name: /Signal|Discuter|Enseignant : révéler/ }).count(), 0)
    // A correct response reveals immediately; no extra click is required.
    await page.getByRole('button', { name: /1.?559/ }).click()
    assert.equal(await page.locator('.ci-answer-correct').count(), 1)
    assert.equal(await page.locator('.ci-reveal').count(), 1)
    assert.equal(await page.locator('.ci-confetti > i').count(), 24)
    assert.equal(await page.locator('.ci-mascot-correct').count(), 1)
    await page.screenshot({ path: `/tmp/clairfle-solo-correct-${width}.png`, fullPage: true })
    assert.equal(await page.locator('.ci-margin-answer').count(), 0)
    await page.clock.runFor(4900)
    assert.match(await page.locator('.ci-progress').innerText(), /Question 1 /)
    await page.clock.runFor(200)
    await page.locator('.ci-progress').filter({ hasText: /Question 2 / }).waitFor()
    assert.match(await page.locator('.ci-progress').innerText(), /Question 2 /)
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    await page.clock.runFor(10000)
    assert.equal(await page.locator('.ci-reveal').count(), 0)
    await page.getByRole('button', { name: 'Reprendre la séance', exact: true }).click()
    await page.clock.runFor(5100)
    await page.locator('.ci-reveal').waitFor()
    assert.equal(await page.locator('.ci-reveal').count(), 1)
    assert.match(await page.locator('.ci-correction-status').innerText(), /sans réponse/)
    assert.equal(await page.locator('.ci-tears > i').count(), 4)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.notEqual(await page.locator('.ci-tears').evaluate((element) => getComputedStyle(element).display), 'none')
    assert.notEqual(await page.locator('.ci-tears > i').first().evaluate((element) => getComputedStyle(element).animationName), 'none')
    assert.notEqual(await page.locator('.ci-mascot-incorrect').evaluate((element) => getComputedStyle(element).animationName), 'none')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.screenshot({ path: `/tmp/clairfle-solo-incorrect-${width}.png`, fullPage: true })
    assert.equal(await page.locator('.ci-margin-answer').count(), 1)
    // Pause also freezes the five seconds of correction.
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    await page.clock.runFor(10000)
    assert.match(await page.locator('.ci-progress').innerText(), /Question 2 /)
    await page.getByRole('button', { name: 'Reprendre la séance', exact: true }).click()
    await page.clock.runFor(5100)
    await page.locator('.ci-progress').filter({ hasText: /Question 3 / }).waitFor()
    assert.match(await page.locator('.ci-progress').innerText(), /Question 3 /)
    await page.locator('.ci-answer').first().click()
    assert.equal(await page.locator('.ci-reveal').count(), 1)
    await page.clock.runFor(5100)
    await page.locator('.ci-progress').filter({ hasText: /Question 4 / }).waitFor()
    assert.match(await page.locator('.ci-progress').innerText(), /Question 4 /)
    assert.equal(await page.locator('.ci-round-question').count(), 1)
    assert.equal(await page.locator('audio').count(), 1)
    // Solo audio never prevents the countdown from starting.
    await page.clock.runFor(5100)
    await page.locator('.ci-reveal').waitFor()
    assert.equal(await page.locator('.ci-reveal').count(), 1)
    for (let question = 5; question <= 10; question++) {
      await page.clock.runFor(5100)
      await page.locator('.ci-progress').filter({ hasText: `Question ${question} /` }).waitFor()
      await page.clock.runFor(5100)
      await page.locator('.ci-reveal').waitFor()
    }
    await page.clock.runFor(5100)
    await page.locator('.ci-summary').waitFor()
    assert.match(await page.locator('.ci-summary').innerText(), /absence de réponse/)
    assert.equal(await page.locator('.ci-summary .ci-panel > p').count(), 10)
    assert.deepEqual(errors, [])
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await mkdir('docs/interactive/screenshots', { recursive: true })
    await page.screenshot({ path: `docs/interactive/screenshots/solo-summary-${width}.png`, fullPage: true })
    results.push({ viewport: `${width}x${height}`, selection: 'automatic correction', timeout: 'incorrect', correctionDelay: '5 seconds', pause: 'both timers suspended', audio: 'timer starts immediately', summary: '10 questions' })
    await page.close()
  }
  await writeFile('docs/interactive/solo-results.json', JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
