const button = (page, name) => page.getByRole('button', { name, exact: true })
async function holdPointer(page, duration) {
  const box = await button(page, 'Enseignant : révéler').boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.clock.runFor(duration)
  await page.mouse.up()
}
async function fits(page, width, height) {
  for (const target of await page.locator('.ci-controls button:visible, .ci-answer:visible, .ci-phase-art:visible, .ci-timer-value:visible').all()) {
    const box = await target.boundingBox()
    assert.ok(box.x >= -1 && box.y >= -1 && box.x + box.width <= width + 1 && box.y + box.height <= height + 1, `Off screen: ${await target.getAttribute('class')} ${JSON.stringify(box)}`)
  }
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
}
