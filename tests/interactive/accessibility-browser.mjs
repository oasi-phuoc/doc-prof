import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const reports = [], errors = []
const button = (page, name) => page.getByRole('button', { name, exact: true })
async function audit(page, state, width) {
  await page.bringToFront()
  await page.evaluate(() => document.fonts.ready)
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()
  await page.bringToFront()
  const violations = result.violations.map((rule) => ({ id: rule.id, impact: rule.impact, targets: rule.nodes.flatMap((node) => node.target) }))
  await writeFile('/tmp/clairfle-axe-last.json', JSON.stringify({ state, width, result }, null, 2))
  assert.deepEqual(violations, [], `${width}px / ${state}: ${JSON.stringify(violations)}`)
  reports.push({ viewport: width, state, violations: 0, passedRules: result.passes.length, manualReviewRules: result.incomplete.map((rule) => rule.id) })
}
try {
  for (const [width, height] of [[390, 844], [1366, 768]]) {
    const context = await browser.newContext({ viewport: { width, height } })
    const page = await context.newPage()
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
    await page.goto(`${base}/interactif/demo`)
    await page.locator('.ci-launch:enabled').waitFor({ timeout: 120000 })
    await audit(page, 'preparation', width)
    await button(page, 'Mascotte').click()
    await audit(page, 'mascot-gallery', width)
    await page.keyboard.press('Escape')
    await page.getByRole('spinbutton', { name: 'Temps de réflexion (secondes)', exact: true }).fill('5')
    await page.clock.install(); await page.clock.pauseAt(new Date(Date.now() + 100))
    await page.locator('.ci-launch').click()
    await page.locator('.ci-timer-value').waitFor()
    assert.equal(await page.locator('.ci-timer-value').getAttribute('aria-live'), 'off')
    await page.clock.runFor(5100)
    await page.getByRole('status').filter({ hasText: 'Temps de réflexion écoulé.' }).waitFor()
    await page.clock.runFor(1500)
    assert.equal(await page.getByRole('status').filter({ hasText: 'Temps de réflexion écoulé.' }).count(), 1)
    await page.clock.resume()
    await audit(page, 'class-thinking', width)
    await button(page, 'Pause').click()
    await audit(page, 'pause', width)
    await button(page, 'Reprendre la séance').last().click()
    await button(page, 'Signal : levez vos cartes').click(); await button(page, 'Discuter').click(); await button(page, 'Enseignant : révéler').click()
    await audit(page, 'class-correction', width)
    await button(page, 'Compter').click()
    await audit(page, 'manual-count-dialog', width)
    await button(page, 'Annuler').click()
    assert.equal(await button(page, 'Compter').evaluate((element) => document.activeElement === element), true)
    await button(page, 'Terminer la séance').click()
    await audit(page, 'finish-confirmation', width)
    await button(page, 'Terminer et voir le bilan').click()
    await audit(page, 'summary', width)
    await button(page, 'Terminer').click()
    await page.locator('.ci-launch:enabled').waitFor()
    await button(page, 'Mode de jeu').click()
    await page.getByRole('checkbox', { name: 'Activer le minuteur', exact: true }).uncheck()
    await button(page, 'Régler le minuteur').click()
    await page.getByRole('spinbutton', { name: 'Temps entre les questions (secondes)', exact: true }).fill('10')
    await button(page, 'Fermer les réglages').click()
    await page.locator('.ci-launch').click()
    await page.locator('.ci-answer:enabled').first().waitFor()
    await audit(page, 'solo-answers', width)
    await page.locator('.ci-answer').first().click()
    assert.equal(await page.getByRole('timer', { name: 'Temps avant la question suivante', exact: true }).getAttribute('aria-live'), 'off')
    await audit(page, 'solo-correction', width)
    await page.goto(`${base}/interactif/cartes`)
    await page.getByRole('heading', { name: 'Cartes de la classe', exact: true }).waitFor()
    await audit(page, 'calibration', width)
    await page.goto(`${base}/interactif/diagnostic`)
    await page.getByRole('heading', { name: 'Diagnostic de l’écran', exact: true }).waitFor()
    await audit(page, 'diagnostic', width)
    await page.goto(`${base}/interactif/demo`)
    await page.locator('.ci-launch:enabled').waitFor()
    if (await button(page, 'Mode de jeu').getAttribute('aria-pressed') === 'true') await button(page, 'Mode de jeu').click()
    await page.locator('.ci-launch').click()
    await page.getByRole('button', { name: /^Choisir une question ·/ }).click()
    await page.getByRole('dialog', { name: 'Choisir une question', exact: true }).locator('li button').last().click()
    await page.locator('.ci-image-zoom').first().click()
    await page.getByRole('dialog', { name: /^Image agrandie :/ }).waitFor()
    await audit(page, 'image-zoom', width)
    await page.keyboard.press('Escape')
    await context.close()
  }
  assert.deepEqual(errors, [])
  await writeFile('docs/interactive/accessibility-results.json', JSON.stringify({ engine: 'axe-core via @axe-core/playwright 4.14.0', tags: ['WCAG 2 A/AA', 'WCAG 2.1 A/AA', 'WCAG 2.2 AA'], reports, errors, limits: 'Automated rules do not replace a screen-reader, zoom, ENI or classroom pilot. Manual-review rules remain listed.' }, null, 2) + '\n')
  console.log(JSON.stringify(reports, null, 2))
} finally { await browser.close() }
