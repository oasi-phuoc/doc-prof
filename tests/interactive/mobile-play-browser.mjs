import { skipQuestion } from './browser-actions.mjs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { writeFile } from 'node:fs/promises'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const results = []
async function fits(page) {
  const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  for (const element of await page.locator('.ci-answer:visible, .ci-controls:visible, .ci-phase-art:visible, .ci-timer-value:visible').all()) {
    const box = await element.boundingBox()
    assert.ok(box.x >= -1 && box.x + box.width <= viewport.width + 1 && box.y >= -1 && box.y + box.height <= viewport.height + 1, `Off-screen game element: ${await element.getAttribute('class')} ${JSON.stringify(box)} / ${JSON.stringify(viewport)}`)
  }
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
}
try {
  for (const [width, height] of [[360, 640], [390, 700], [430, 800]]) {
    const page = await browser.newPage({ viewport: { width, height }, hasTouch: true })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
    await page.goto(`${base}/interactif/demo`)
    await page.getByRole('button', { name: /Commencer la séance/ }).waitFor({ timeout: 120000 })
    const mode = page.getByRole('button', { name: 'Mode de jeu', exact: true })
    assert.equal(await mode.getAttribute('aria-pressed'), 'false')
    await mode.click()
    assert.equal(await mode.getAttribute('aria-pressed'), 'true')
    assert.equal(await page.getByRole('dialog', { name: 'Choisir le mode de jeu' }).count(), 0)
    await mode.click()
    assert.equal(await mode.getAttribute('aria-pressed'), 'false')
    await page.getByRole('button', { name: 'Régler le minuteur', exact: true }).click()
    const settings = page.getByRole('dialog', { name: 'Réglages du minuteur' })
    const bounds = await settings.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width && bounds.y + bounds.height <= height)
    const gap = settings.getByRole('spinbutton', { name: 'Temps entre les questions (secondes)', exact: true })
    assert.equal(await gap.getAttribute('min'), '1')
    assert.equal(await gap.getAttribute('max'), '10')
    assert.equal(await gap.inputValue(), '5')
    await gap.fill('1')
    await page.getByRole('button', { name: 'Fermer les réglages', exact: true }).click()
    await mode.click()
    await page.clock.install()
    await page.clock.pauseAt(new Date(Date.now() + 1000))
    await page.getByRole('button', { name: /Commencer la séance/ }).click()
    await page.locator('.ci-controls').waitFor()
    assert.equal(await page.getByRole('link', { name: 'Créer des fiches', exact: true }).count(), 0)
    await fits(page)
    await page.getByRole('button', { name: 'Plein écran', exact: true }).click()
    await page.locator('.ci-immersive').waitFor()
    assert.deepEqual(await page.locator('.ci-header button:visible').evaluateAll((elements) => elements.map((element) => element.getAttribute('aria-label'))), ['Quitter le plein écran'])
    await fits(page)
    await page.getByRole('button', { name: 'Quitter le plein écran', exact: true }).click()
    await page.locator('.ci-app:not(.ci-immersive)').waitFor()
    await page.getByRole('button', { name: /1.?559/ }).click()
    await page.locator('.ci-controls [role="timer"]').filter({ hasText: 'Question suivante dans 1 s' }).waitFor()
    await fits(page)
    await page.clock.runFor(900)
    assert.match(await page.locator('.ci-progress').innerText(), /Question 1 /)
    await page.clock.runFor(200)
    await page.locator('.ci-progress').filter({ hasText: /Question 2 / }).waitFor()
    await page.getByRole('button', { name: 'Régler le minuteur', exact: true }).click()
    await page.getByRole('spinbutton', { name: 'Temps entre les questions (secondes)', exact: true }).fill('10')
    await page.getByRole('button', { name: 'Fermer les réglages', exact: true }).click()
    await page.locator('.ci-answer').filter({ hasNotText: /83/ }).first().click()
    await page.locator('.ci-controls [role="timer"]').filter({ hasText: 'Question suivante dans 10 s' }).waitFor()
    await fits(page)
    await page.clock.runFor(9900)
    assert.match(await page.locator('.ci-progress').innerText(), /Question 2 /)
    await page.clock.runFor(200)
    await page.locator('.ci-progress').filter({ hasText: /Question 3 / }).waitFor()
    await skipQuestion(page)
    await page.locator('audio').waitFor()
    await page.locator('audio').evaluate((audio) => { audio.dataset.keep = 'same-player' })
    await page.getByRole('button', { name: 'Plein écran', exact: true }).click()
    await page.locator('.ci-immersive').waitFor()
    assert.equal(await page.locator('audio').getAttribute('data-keep'), 'same-player')
    assert.equal(await page.locator('audio').isVisible(), true)
    await fits(page)
    await page.getByRole('button', { name: 'Quitter le plein écran', exact: true }).click()
    await page.getByRole('button', { name: 'Quitter la séance', exact: true }).click()
    await page.getByRole('button', { name: /Reprendre la séance/ }).waitFor()
    assert.equal(await page.getByRole('link', { name: 'Créer des fiches', exact: true }).count(), 1)
    await page.getByRole('button', { name: 'Régler le minuteur', exact: true }).click()
    assert.equal(await page.getByRole('spinbutton', { name: 'Temps entre les questions (secondes)', exact: true }).inputValue(), '10')
    assert.deepEqual(errors, [])
    results.push({ viewport: `${width}x${height}`, toggle: 'class/solo pushbutton without menu', timerPanel: 'fully inside viewport', feedback: '1 and 10 seconds executed', gameFit: 'question, six cards, timer and controls on screen', immersive: 'fullscreen button only; same audio player retained', createFiches: 'preparation only', errors })
    await page.close()
  }
  const fallback = await browser.newPage({ viewport: { width: 390, height: 640 }, hasTouch: true })
  await fallback.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
  await fallback.addInitScript(() => { Element.prototype.requestFullscreen = undefined })
  await fallback.goto(`${base}/interactif/demo`)
  await fallback.getByRole('button', { name: /Commencer la séance/ }).waitFor({ timeout: 120000 })
  await fallback.getByRole('button', { name: /Commencer la séance/ }).click()
  await fallback.locator('.ci-controls').waitFor()
  await fallback.getByRole('button', { name: 'Plein écran', exact: true }).click()
  await fallback.locator('.ci-immersive').waitFor()
  assert.equal(await fallback.locator('.ci-header button:visible').count(), 1)
  await fits(fallback)
  await fallback.getByRole('button', { name: 'Quitter le plein écran', exact: true }).click()
  await fallback.locator('.ci-app:not(.ci-immersive)').waitFor()
  results.push({ embeddedBrowser: 'immersive mode and exit work without native fullscreen API' })
  await writeFile('docs/interactive/mobile-play-results.json', JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
