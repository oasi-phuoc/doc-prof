import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { readFile, writeFile } from 'node:fs/promises'
const base = process.env.INTERACTIVE_TEST_URL ?? 'http://127.0.0.1:5180'
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined, args: ['--no-sandbox'] })
const results = []
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true })
  const errors = []
  const apiRequests = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => { if (/workers\.dev|\/api\/fiches/.test(request.url())) apiRequests.push(request.url()) })
  await page.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
  await page.goto(`${base}/interactif/diagnostic`)
  await page.getByRole('heading', { name: 'Diagnostic de l’écran', exact: true }).waitFor({ timeout: 120000 })
  assert.equal(await page.locator('.ci-question-list').count(), 0)
  assert.match(await page.getByRole('textbox', { name: 'Rapport de diagnostic' }).inputValue(), /Stockage local.*non testé/)
  await page.getByRole('button', { name: 'Tester le stockage', exact: true }).click()
  await page.locator('[data-diagnostic-storage]').filter({ hasText: 'disponible' }).waitFor()
  assert.match(await page.locator('[data-diagnostic-storage]').innerText(), /^Stockage : disponible/)
  await page.getByRole('button', { name: 'Tester le son', exact: true }).click()
  await page.locator('[data-diagnostic-audio]').filter({ hasText: 'lecture démarrée après un geste' }).waitFor()
  assert.match(await page.locator('[data-diagnostic-audio]').innerText(), /lecture démarrée après un geste/)
  for (let n = 1; n <= 10; n++) {
    await page.getByRole('button', { name: /Cible ·/ }).tap()
    await page.getByRole('button', { name: `Cible · ${n}/10`, exact: true }).waitFor()
  }
  assert.match(await page.locator('[data-diagnostic-latency]').innerText(), /^10\/10/)
  const zone = page.locator('.ci-diagnostic-contact')
  await zone.scrollIntoViewIfNeeded()
  const box = await zone.boundingBox()
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + 30, y: box.y + 30, id: 1 }, { x: box.x + 90, y: box.y + 70, id: 2 }] })
  assert.match(await zone.innerText(), /maximum observé 2/)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.match(await zone.innerText(), /contacts : 0/)
  await page.getByRole('button', { name: 'Aplat F', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Aplat F', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('region', { name: 'Aplat de contrôle', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.getByRole('button', { name: 'Aplat A', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'Tester le plein écran', exact: true }).click()
  await page.locator('[data-diagnostic-fullscreen]').filter({ hasText: /test réussi|refusée|API absente/ }).waitFor({ state: 'attached' })
  const fullscreen = await page.locator('[data-diagnostic-fullscreen]').innerText()
  assert.match(fullscreen, /test réussi|refusée|API absente/)
  if (await page.evaluate(() => !!document.fullscreenElement)) await page.getByRole('button', { name: 'Quitter le plein écran', exact: true }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Télécharger le rapport', exact: true }).click()
  const download = await downloadEvent
  assert.equal(download.suggestedFilename(), 'diagnostic-eni.md')
  await download.saveAs('/tmp/clairfle-diagnostic-eni.md')
  const report = await readFile('/tmp/clairfle-diagnostic-eni.md', 'utf8')
  assert.match(report, /10\/10 mesures/)
  assert.match(report, /Contacts simultanés observés : 2/)
  assert.match(report, /Stockage local.*disponible/)
  assert.ok(!report.includes('clairfle-fiche-access'))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.reload()
  await page.getByRole('heading', { name: 'Diagnostic de l’écran', exact: true }).waitFor()
  assert.deepEqual(apiRequests, [])
  assert.deepEqual(errors, [])
  results.push({ viewport: '390x844', storage: 'native write/read/delete probe', sound: 'native audio context starts after gesture', pointers: '10 measured touches and 2 simultaneous contacts', colors: '6 swatches; keyboard cycles', fullscreen, report: 'downloaded and validated', reload: 'direct route; no fiche API requests' })
  await page.close()

  const fallback = await browser.newPage()
  const fallbackErrors = []
  fallback.on('pageerror', (error) => fallbackErrors.push(error.message))
  await fallback.context().addCookies([{ name: 'clairfle-fiche-access', value: 'admin', url: base }])
  await fallback.addInitScript(() => {
    indexedDB.open = () => { throw new DOMException('Blocked', 'SecurityError') }
    Object.defineProperty(window, 'AudioContext', { value: undefined })
    Object.defineProperty(window, 'webkitAudioContext', { value: undefined })
    Object.defineProperty(navigator, 'clipboard', { value: undefined })
    Object.defineProperty(navigator, 'wakeLock', { value: { request: () => Promise.reject(new DOMException('Denied', 'NotAllowedError')) } })
    Element.prototype.requestFullscreen = undefined
  })
  await fallback.goto(`${base}/interactif/diagnostic`)
  await fallback.getByRole('heading', { name: 'Diagnostic de l’écran', exact: true }).waitFor()
  await fallback.getByRole('button', { name: 'Tester le stockage', exact: true }).click()
  await fallback.locator('[data-diagnostic-storage]').filter({ hasText: 'refusé' }).waitFor()
  await fallback.getByRole('button', { name: 'Tester le son', exact: true }).click()
  assert.match(await fallback.locator('[data-diagnostic-audio]').innerText(), /API audio indisponible/)
  await fallback.getByRole('button', { name: 'Tester le plein écran', exact: true }).click()
  assert.match(await fallback.locator('[data-diagnostic-fullscreen]').innerText(), /API absente/)
  await fallback.getByRole('button', { name: 'Tester le maintien éveillé', exact: true }).click()
  await fallback.locator('[data-diagnostic-wake]').filter({ hasText: 'refusée' }).waitFor()
  await fallback.getByRole('button', { name: 'Copier le rapport', exact: true }).click()
  assert.match(await fallback.locator('body').innerText(), /Sélectionnez et copiez le rapport/)
  assert.deepEqual(fallbackErrors, [])
  results.push({ unavailableApis: 'storage blocked, audio absent, fullscreen absent, wake lock denied, clipboard manual fallback; no crash' })
  await fallback.close()
  const anonymous = await browser.newPage()
  await anonymous.goto(`${base}/interactif/diagnostic`)
  await anonymous.waitForURL('**/acces')
  await anonymous.close()
  results.push({ anonymous: 'existing access gate retained' })
  await writeFile('docs/interactive/diagnostic-results.json', JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
